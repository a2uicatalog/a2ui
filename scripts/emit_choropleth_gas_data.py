#!/usr/bin/env python3
"""Writes the Apps Script copies of the choropleth_map region data from atoms/geo (the single source): atoms_choropleth_data.gs in gas-wired-renderer
(gas-schema-renderer is frozen and gets no copy). tests/test_choropleth_map.py checks the committed file equals render(). Not a bundle generator."""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GEO = ROOT / "atoms" / "geo"
GAS = ROOT / "apps-script-surface"
HEAD = ("// GENERATED by scripts/emit_choropleth_gas_data.py from atoms/geo/*.json (Natural Earth 110m via world-atlas@2 and US Census 10m via us-atlas@3, ISC; see atoms/geo/README.md).\n"
        "// Do not edit by hand. Twin of the data the Python renderer reads from atoms/geo; used by atoms_choropleth.gs at render time only.\n")


def render() -> str:
    parts = ",\n".join('"%s":%s' % (n, (GEO / (n + ".json")).read_text(encoding="utf-8")) for n in ("world-countries", "us-states", "europe-countries"))
    return HEAD + "var _CH_GEO = {\n" + parts + "\n};\n"


def main():
    d = render()
    (GAS / "gas-wired-renderer/atoms_choropleth_data.gs").write_text(d, encoding="utf-8")


if __name__ == "__main__":
    main()
