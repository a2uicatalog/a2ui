#!/usr/bin/env python3
"""Builds public/try-mermaid/: the Mermaid / D2 paste window (index.html, try-mermaid.js, try-mermaid.css, convert.worker.js).

The worker is the converter in scripts/mermaid_arch (the ES modules joined into one classic script, the same way build_playground.mjs does it)
plus scripts/try_mermaid/worker_main.js, which enforces the limits again inside the worker. Other pages mount the window with one include:

    <link rel="stylesheet" href="/try-mermaid/try-mermaid.css">
    <div id="try-mermaid" data-worker="/try-mermaid/convert.worker.js" data-bundle="https://play.a2uicatalog.ai/renderer-bundle?v=<hash>"></div>
    <script src="/try-mermaid/try-mermaid.js"></script>
    <script>TryMermaid.mount(document.getElementById('try-mermaid'), {compact: false})</script>

Usage: python3 scripts/gen_try_mermaid.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

ARCH = ROOT / "scripts" / "mermaid_arch"
SRC = ROOT / "scripts" / "try_mermaid"
OUT = ROOT / "public" / "try-mermaid"
# dependency order; index.mjs last (it re-exports), d2.mjs after mermaid.mjs (it imports from it and from graph.mjs)
MODULES = ["graph.mjs", "labels.mjs", "schedule.mjs", "activity.mjs", "mermaid.mjs", "d2.mjs", "route.mjs", "layout.mjs", "compile.mjs", "index.mjs"]
# True since 2 Nov 2026: a headless-browser network log (every request from the page, the worker and the renderer frame, URLs and POST bodies) showed no request carrying the diagram text; the only POST is the renderer origin's Cloudflare analytics beacon. Set it back to False if the renderer bundle ever starts sending the payload anywhere.
NO_UPLOAD_VERIFIED = True


def worker_script():
    parts = []
    for f in MODULES:
        s = (ARCH / f).read_text()
        s = re.sub(r"^import[^;]*;\s*$", "", s, flags=re.M)
        s = re.sub(r"^export \{[^}]*\}( from '[^']*')?;\s*$", "", s, flags=re.M)
        s = re.sub(r"^export (async )?(function|class|const|let) ", r"\1\2 ", s, flags=re.M)
        parts.append(f"// ---- {f}\n{s}")
    code = "\n".join(parts)
    if re.search(r"^\s*(import|export)\s", code, flags=re.M):
        raise SystemExit("unprocessed import/export left in the worker bundle")
    main = (SRC / "worker_main.js").read_text()
    return "/* Generated by scripts/gen_try_mermaid.py from scripts/mermaid_arch and scripts/try_mermaid/worker_main.js. Do not edit. */\n'use strict';\n" + code + "\n" + main


def page_html():
    import generate_atom_pages as g
    bundle = f"https://play.a2uicatalog.ai/renderer-bundle?v={g._bundle_hash()}"
    full = g.render_try_page(0)
    footer = re.search(r"<footer>.*?</footer>", full, flags=re.S).group(0)
    nu = ' data-noupload="1"' if NO_UPLOAD_VERIFIED else ""
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <link rel="icon" href="/favicon.ico" sizes="32x32">
  <link rel="apple-touch-icon" href="/apple-touch-icon.png">
  <link rel="manifest" href="/site.webmanifest">
  <meta name="theme-color" content="#5051cf">
  <meta name="viewport" content="width=device-width,initial-scale=1.0">
  <title>Mermaid to film — A2UI Atomic Catalog</title>
  <meta name="description" content="Paste a Mermaid flowchart or a D2 diagram and watch it draw itself as a numbered, paced film.">
  <meta name="robots" content="noindex, nofollow">
  {g.SITE_HEAD_JS}
  {g.PAGE_CSS}
  <link rel="stylesheet" href="/try-mermaid/try-mermaid.css">
</head>
<body>
  {g.site_header("")}
  <div class="wrap">
  <nav class="crumb"><a href="/">A2UI Catalog</a> / mermaid to film</nav>
  <h1>Mermaid to film</h1>
  <p class="desc">Paste a Mermaid flowchart or a D2 diagram. It is laid out, numbered and paced, and plays as a film. Limits: 12 nodes, 16 edges, 20,000 characters.</p>
  <div id="try-mermaid" data-worker="/try-mermaid/convert.worker.js" data-bundle="{bundle}"{nu}>
    <noscript><p>This tool needs JavaScript. The converter is open source in <code>scripts/mermaid_arch</code> in the repository.</p></noscript>
  </div>
  {footer}
  </div>
  {g.SITE_FOOT_JS}
  <script src="/try-mermaid/try-mermaid.js"></script>
  <script>TryMermaid.mount(document.getElementById('try-mermaid'), {{compact: false}});</script>
</body>
</html>
"""


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "convert.worker.js").write_text(worker_script())
    (OUT / "try-mermaid.js").write_text((SRC / "try-mermaid.js").read_text())
    (OUT / "try-mermaid.css").write_text((SRC / "try-mermaid.css").read_text())
    (OUT / "index.html").write_text(page_html())
    for f in sorted(OUT.iterdir()):
        print("wrote", f.relative_to(ROOT), f.stat().st_size)


if __name__ == "__main__":
    main()
