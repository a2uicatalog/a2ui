BASE = "https://a2uicatalog.ai"


def _counts():
    if not os.path.isfile(SPEC):
        sys.exit("public/spec.json missing — run scripts/gen_public_catalog.py first")
    with open(SPEC, encoding="utf-8") as f:
        spec = json.load(f)
    atoms = spec.get("atoms") or spec.get("blocks") or []
    n = spec.get("atomCount") or len(atoms)
    surfaces = set()
    for a in atoms:
        for s in ((a.get("surfaces") or {}).get("works_on") or []):
            surfaces.add(s)
    mcp = sum(1 for a in atoms
              if "mcp-apps" in ((a.get("surfaces") or {}).get("works_on") or []))
    return n, len(surfaces), mcp


