"""gen_openapi.py — compile public/openapi.json and public/llms.txt.

Both documents state the size of the catalogue ("474 typed UI atoms"), and
both were originally hand-written with that number baked in — so every atom
added silently made the two most agent-facing documents on the site wrong.
They are compiled here from public/spec.json (the PUBLISHED artifact, so the
count already reflects the stage/visibility filter) exactly like
gen_compat_matrix.py and gen_readme_badges.py do.

Publishing an OpenAPI document at all is the fix for a concrete finding: an
agent-readiness audit (2026-07-31) scored the site 0/7 on "OpenAPI spec
published" and 0/6 on "developer portal", and its agent review concluded
"impossible to proceed with any integration".

Run:
  python3 scripts/gen_openapi.py            # after gen_public_catalog.py
"""
