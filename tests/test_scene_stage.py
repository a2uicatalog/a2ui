import shutil
import subprocess
from pathlib import Path

import pytest
import yaml

ROOT = Path(__file__).resolve().parent.parent
GAS = ROOT / "apps-script-surface" / "gas-wired-renderer"
FILES = sorted(GAS.glob("atoms_scene*.gs"))            # the estate concatenates atoms_*.gs in sorted order
NODE = shutil.which("node")


def test_the_atoms_sit_in_the_effects_pack_and_no_new_dangling_catalogue_is_advertised():
    """A new extension pack would be advertised in the public index without a catalogue file (test_staging forbids growing that debt),
    so the scene atoms live in a2ui-effects-v1, whose selection text names them."""
    packs = yaml.safe_load((ROOT / "atoms" / "atom-packs.yaml").read_text())
    assert "a2ui-scenes-v1" not in packs
    assert {"clipart", "scene_stage"} <= set(packs["a2ui-effects-v1"])
    assert "scene_stage" in (ROOT / "scripts" / "gen_catalog_index.py").read_text()


def test_the_atoms_are_public_stable_and_no_longer_declared_debt():
    """Promoted 2026-09-20 (Curtis: publish them publicly): definitions live in the public schema, stable, no visibility flag."""
    blocks = {b["type"]: b for b in yaml.safe_load((ROOT / "atoms" / "schema.yaml").read_text())["blocks"] if isinstance(b, dict)}
    for t_ in ("scene_stage", "clipart"):
        assert t_ in blocks and blocks[t_].get("stage", "stable") == "stable" and "visibility" not in blocks[t_], t_
        assert blocks[t_]["source"]["license"] == "MIT"
        assert "mcp-apps" in blocks[t_]["surfaces"]["works_on"]
    debt = yaml.safe_load((ROOT / "project.yaml").read_text())["known_debt"]["unregistered_atoms"]
    assert not ({"scene_stage", "clipart"} & set(debt)), "no longer schema-absent"


def test_generated_files_are_marked_and_split_engine_from_data():
    assert [f.name for f in FILES] == ["atoms_scene.gs", "atoms_scene_data.gs"]
    for f in FILES:
        assert f.read_text().startswith("// GENERATED by scene-atom/gen_scene_gs.py"), f.name
    engine, data = (f.read_text() for f in FILES)
    assert "_RENDERERS['scene_stage']" in engine and "_RENDERERS['clipart']" in engine
    assert "var SCENE_STAGE_DATA = " in data and "SCENE_STAGE_DATA" in engine
    for banned in ("import.meta", "fetch(", "document.", "window.", "localStorage", "require("):
        assert banned not in engine, banned


def test_python_static_renderer_degrades_visibly_and_escapes_payload_text():
    from renderers.web_article import _RENDERERS
    html = _RENDERERS["scene_stage"]({"type": "scene_stage", "preset": "data-centre", "title": "<script>alert(1)</script>"})
    assert "<script" not in html and "&lt;script&gt;" in html and "data-centre" in html and "MCP Apps" in html
    clip = _RENDERERS["clipart"]({"type": "clipart", "asset": "desk", "alt": 'a "desk" <b>'})
    assert "<b>" not in clip and "&quot;desk&quot;" in clip
    assert "clipart" in _RENDERERS["clipart"]({"type": "clipart"}), "even an empty block must not render nothing"


@pytest.mark.skipif(NODE is None, reason="node is not installed")
def test_gas_files_render_scenes_in_a_bare_runtime_without_a_dom():
    js = r"""
    const vm = require('vm'), fs = require('fs'); const ctx = vm.createContext({});
    vm.runInContext('var _RENDERERS = {};', ctx);
    for (const f of JSON.parse(process.argv[1])) vm.runInContext(fs.readFileSync(f, 'utf8'), ctx);   // sorted, as the estate loads them
    const run = (src) => vm.runInContext(src, ctx);
    ctx.b1 = {type: 'scene_stage', preset: 'data-centre'};
    ctx.b2 = {type: 'scene_stage', preset: 'wind-farm', title: '<script>alert(1)</script>', theme: {time: 'night'}};
    ctx.b3 = {type: 'scene_stage', preset: 'no-such-place'};
    ctx.c1 = {type: 'clipart', asset: 'desk', scale: 2, flip: true, label: 'A desk'};
    ctx.c2 = {type: 'clipart', asset: 'not-a-prop'};
    const out = {textEncoder: run('typeof TextEncoder'), globals: Object.keys(ctx).filter(k => !/^[bc]\d$/.test(k)).sort(),
      renderers: Object.keys(ctx._RENDERERS).sort(),
      s1: run('_RENDERERS.scene_stage(b1)'), s2: run('_RENDERERS.scene_stage(b2)'), s3: run('_RENDERERS.scene_stage(b3)'),
      c1: run('_RENDERERS.clipart(c1)'), c2: run('_RENDERERS.clipart(c2)')};
    console.log(JSON.stringify(out));
    """
    r = subprocess.run([NODE, "-e", js, json.dumps([str(f) for f in FILES])], capture_output=True, text=True, timeout=120)
    assert r.returncode == 0, r.stderr
    o = json.loads(r.stdout)
    assert o["textEncoder"] == "undefined" and o["globals"] == ["SCENE_STAGE_DATA", "SceneStage", "_RENDERERS"]
    assert o["renderers"] == ["clipart", "scene_stage"]
    for k in ("s1", "s2"):
        assert o[k].startswith('<figure class="a2ui-scene"') and "<animate" in o[k] and "scene-atom:provenance" in o[k], k
        assert not re.search(r"<script|onload=|onclick=|javascript:", o[k]), f"{k}: the drawn scene must contain no script"
    assert "&lt;script&gt;" in o["s2"], "titles are escaped"
    prov = json.loads(re.search(r"<scene-atom:provenance[^>]*>(.*?)</scene-atom:provenance>", o["s1"]).group(1).replace("&quot;", '"').replace("&amp;", "&"))
    assert prov["assets"] and all(a["license"] == "MIT" and len(a["sha256"]) == 64 for a in prov["assets"])
    assert "spec.preset must be one of" in o["s3"] and "no-such-place" not in o["s3"].split("one of")[0]
    assert o["c1"].startswith('<figure class="a2ui-clipart"') and "scale(-1 1)" in o["c1"] and "A desk" in o["c1"]
    assert "stable registry ids" in o["c2"]


