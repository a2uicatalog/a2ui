@pytest.mark.skipif(NODE is None, reason="node is not installed")
def test_a_layout_without_scenery_actors_or_camera_still_renders_and_a_bad_one_says_what_is_wrong():
    """Found by a blind LLM-style test: a model writing a layout in full may leave out actors/scenery/camera; those default."""
    js = r"""
    const vm = require('vm'), fs = require('fs'); const ctx = vm.createContext({}); vm.runInContext('var _RENDERERS = {};', ctx);
    for (const f of JSON.parse(process.argv[1])) vm.runInContext(fs.readFileSync(f, 'utf8'), ctx);
    ctx.ok = {type: 'scene_stage', backdrop: 'interior-office', ground: 'concrete', stage: {width: 1400, zoom: 1300, focus_y: -260}, scenery: [{prop: 'desk', x: 600}]};
    ctx.bare = {type: 'scene_stage', backdrop: 'sky-hills', ground: 'grass', stage: {width: 1400, zoom: 1300, focus_y: -260}};
    ctx.bad = {type: 'scene_stage', backdrop: 'sky-hills', stage: {width: 1400, zoom: 1300, focus_y: -260}};
    console.log(JSON.stringify(['ok', 'bare', 'bad'].map(k => vm.runInContext('_RENDERERS.scene_stage(' + k + ')', ctx))));
    """
    r = subprocess.run([NODE, "-e", js, json.dumps([str(f) for f in FILES])], capture_output=True, text=True, timeout=120)
    assert r.returncode == 0, r.stderr
    ok, bare, bad = json.loads(r.stdout)
    assert ok.startswith("<figure") and bare.startswith("<figure") and "<animate" in ok
    assert "spec.ground must be one of" in bad


@pytest.mark.skipif(NODE is None, reason="node is not installed")
def test_the_mcp_apps_bundle_itself_renders_scenes_and_clipart():
    """Build the real MCP Apps bundle in memory, run its DOM-free core in Node, and render both atoms through renderAtoms."""
    import sys
    import tempfile
    sys.path.insert(0, str(ROOT / "scripts"))
    import gen_mcp_apps_bundle as g
    bundle = g.build_bundle()
    core = [b for b in re.findall(r"<script>\n(.*?)\n</script>", bundle, re.S) if "a2ui-core" in b[:300]][0]
    blocks = [{"type": "scene_stage", "preset": "wind-farm", "theme": {"time": "dusk"}}, {"type": "scene_stage", "preset": "no-such"},
              {"type": "clipart", "asset": "wind-turbine", "scale": 1.5, "label": "A turbine"}]
    with tempfile.TemporaryDirectory() as td:
        driver = Path(td) / "driver.js"
        driver.write_text("global.window = global;\n" + core + "\nvar out = " + json.dumps(blocks) +
                          ".map(function (b) { return renderAtoms([b], {theme: 'light'}); });\nconsole.log(JSON.stringify(out));\n")
        proc = subprocess.run([NODE, str(driver)], capture_output=True, text=True, timeout=120)
    assert proc.returncode == 0, proc.stderr[-2000:]
    scene, bad, clip = json.loads(proc.stdout)
    assert 'class="a2ui-scene"' in scene and "<animate" in scene and "scene-atom:provenance" in scene, scene[:300]
    assert "not bundled on this surface" not in scene and "spec.preset must be one of" in bad
    assert 'class="a2ui-clipart"' in clip and "A turbine" in clip
    assert len(bundle) < 3_200_000


def test_published_scene_assets_match_the_data_the_renderer_embeds():
    """public/catalogue/assets-index-v1.json and scene-spec.schema.json are generated by the kit (diagram-studio/scene-atom) and copied
    here; they must describe exactly what atoms_scene_data.gs embeds, or an agent is offered props the renderer refuses."""
    idx = json.loads((ROOT / "public" / "catalogue" / "assets-index-v1.json").read_text())
    data_src = (GAS / "atoms_scene_data.gs").read_text()
    data = json.loads(data_src.split("var SCENE_STAGE_DATA = ", 1)[1].rsplit(";", 1)[0])
    assert idx["registry_sha256"] == data["registry_sha256"], "index and embedded data come from different registries: recopy from the kit"
    embedded = {e["id"] for e in data["entries"]}
    assert {a["id"] for a in idx["assets"]} <= embedded and all(a["stage"] == "stable" for a in idx["assets"])
    assert {p["id"] for p in idx["presets"]} == set(data["layouts"]["layouts"])
    schema = json.loads((ROOT / "public" / "catalogue" / "scene-spec.schema.json").read_text())
    assert set(schema["properties"]["preset"]["enum"]) == set(data["layouts"]["layouts"])
    assert set(schema["properties"]["scenery"]["items"]["properties"]["prop"]["enum"]) >= {a["id"] for a in idx["assets"]}
