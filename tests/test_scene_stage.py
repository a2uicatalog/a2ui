"""scene_stage / clipart: the scene-atom kit's atoms.

Their schema blocks are visibility:private and live in a2ui-private/private-atoms/; what is public is the renderer (the estate's
shared infra), the pack entry and the declared debt. These tests pin that split and prove the generated GAS files render in a bare
runtime (no DOM, no TextEncoder), the way Apps Script and the Worker run renderers.
"""
import json
