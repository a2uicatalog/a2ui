def test_every_page_declares_a_document_language():
    """axe html-has-lang (WCAG 3.1.1): <html> needs a lang attribute. A fragment page with no <html> tag at all counts as missing."""
    bad = []
    for p in _site_pages():
        rel = str(p.relative_to(ROOT))
        if rel in LANG_EXEMPT:
            continue
        m = re.search(r"<html\b[^>]*>", p.read_text(errors="ignore"), re.I)
        if not m or not re.search(r"\blang=[\"']?[a-zA-Z]", m.group(0)):
            bad.append(rel)
    assert not bad, f"pages without <html lang>: {bad}"


# axe svg-img-alt (WCAG 1.1.1): an <svg> in the page is either decorative (aria-hidden="true") or a named image (role="img" plus aria-label / aria-labelledby / <title>).
SVG_EXEMPT = {
    "public/surfaces/mcp-apps/renderer-bundle.html",   # the <svg> strings are JavaScript source; see LANG_EXEMPT
    "public/surfaces/amiga/index.html",                # third-party Amiga emulator UI, not ours
}


def _svg_defects(html):
    html = re.sub(r"<!--.*?-->", "", html, flags=re.S)
    html = re.sub(r"<(script|style)\b.*?</\1>", "", html, flags=re.S | re.I)
    html = re.sub(r"url\((?:&quot;|[\"'\\])*data:image/svg[^)]*\)", "", html, flags=re.I)   # a CSS background image is not DOM
    bad = []
    for m in re.finditer(r"<svg\b[^>]*>", html, re.I):
        head = m.group(0)
        if re.search(r"aria-hidden=[\"']true[\"']", head):
            continue
        named = re.search(r"aria-label(?:ledby)?=[\"'][^\"']+[\"']", head) or re.match(r"\s*<title\b", html[m.end():])
        if re.search(r"role=[\"']img[\"']", head) and named:
            continue
        bad.append(head[:90])
    return bad


def test_every_svg_is_hidden_or_named():
    bad = {}
    for p in _site_pages():
        rel = str(p.relative_to(ROOT))
        if rel in SVG_EXEMPT:
            continue
        d = _svg_defects(p.read_text(errors="ignore"))
        if d:
            bad[rel] = (len(d), d[0])
    assert not bad, f"unnamed <svg> in {len(bad)} page(s): {dict(list(bad.items())[:6])}"


# axe aria-required-children (WCAG 1.3.1): the owned elements of a tablist are tabs and nothing else.
TABLIST_EXEMPT = {"public/surfaces/diagram-studio/view.html"}   # zoom buttons sit inside the tablist; the view is versioned by the MCP worker (UI_VIEW_URI), so the fix waits for a bump


def _tablist_stray_children(html):
    from html.parser import HTMLParser
    VOID = {"br", "hr", "img", "input", "meta", "link", "area", "base", "col", "embed", "source", "track", "wbr"}

    class P(HTMLParser):
        def __init__(self):
            super().__init__()
            self.stack, self.stray = [], []

        def handle_starttag(self, tag, attrs):
            a = dict(attrs)
            if self.stack and self.stack[-1][0] == "tablist" and a.get("role") != "tab" and a.get("role") not in ("presentation", "none"):
                self.stray.append(f"<{tag}> in tablist")
            if tag not in VOID:
                self.stack.append((a.get("role") or "", tag))

        def handle_endtag(self, tag):
            for i in range(len(self.stack) - 1, -1, -1):
                if self.stack[i][1] == tag:
                    del self.stack[i:]
                    break
    p = P()
    html = re.sub(r"<(script|style)\b.*?</\1>", "", html, flags=re.S | re.I)
    p.feed(html)
    return p.stray


def test_tablist_owns_only_tabs():
    bad = {}
    for p in _site_pages():
        rel = str(p.relative_to(ROOT))
        if rel in TABLIST_EXEMPT or rel in SVG_EXEMPT:
            continue
        t = p.read_text(errors="ignore")
        if 'role="tablist"' in t:
            s = _tablist_stray_children(t)
            if s:
                bad[rel] = s[:3]
    assert not bad, f"tablist with non-tab children: {bad}"


def test_published_pages_do_not_hide_radios_with_display_none():
    """Same rule as the renderer check above, on the shipped HTML (the gallery article pages carried a stale copy of the old carousel CSS)."""
    bad = []
    for p in _site_pages():
        t = p.read_text(errors="ignore")
        if re.search(r"input(?:\[type=(?:radio|checkbox)\])?\s*\{\s*display:\s*none", t) and re.search(r"type=[\"']?(?:radio|checkbox)", t):
            bad.append(str(p.relative_to(ROOT)))
    assert not bad, f"radio/checkbox hidden with display:none in {bad}"
