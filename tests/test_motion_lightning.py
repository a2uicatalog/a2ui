# ─── WCAG 2.3.1: bounded flashes, whatever duration p is played over ───────────
def _sin_rads(h):
    """every sin(...) argument of the form var(--p,1)*F + PH, as F"""
    return [float(m) for m in re.findall(r'sin\(calc\(var\(--p,1\)\*([\d.]+) \+ [\d.]+\)\)', h)]


def _flash_peak_and_colour(h):
    m = re.search(r'<[^>]*data-lt="flash"[^>]*>', h)
    st = m.group(0)
    col = re.search(r'background:rgb\((\d+),(\d+),(\d+)\)', st)
    pk = re.search(r'opacity:calc\(([\d.]+)\*', st)
    return tuple(int(x) for x in col.groups()), float(pk.group(1))


def test_the_flicker_and_the_flash_never_make_more_than_three_flashes():
    """Parsing the output: every flicker sinusoid swings under one full cycle (<= 2*pi rad) over p 0..1, so it is at most one flash; the flash is a
    single pulse (one flash). Together at most 2, inside the limit of 3 for any duration p is played over. Checked over many seeds and settings."""
    import math
    worst = 0
    for s in list(range(0, 400, 7)) + [9999, 4242]:
        for bolts in (1, 3, 6):
            h = _py(dict(BASE, seed=s, bolts=bolts, branches=4, flash=True))
            rads = _sin_rads(h)
            assert rads, "the flicker is a sinusoid in p"
            assert all(r <= 6.0 for r in rads), rads
            # all bolts share one frequency, so their sum is itself one sinusoid: one cycle at most
            assert len(set(rads)) == 1, rads
            flashes = max(rads) / (2 * math.pi) + len(re.findall(r'data-lt="flash"', h))
            worst = max(worst, flashes)
            assert flashes <= 2 + 1e-9, (s, flashes)
            assert len(re.findall(r'data-lt="flash"', h)) == 1
    assert worst <= 3
    # nothing else in the output oscillates: no keyframes, no second sin() family, no steps()
    h = _py(dict(BASE, flash=True))
    assert "steps(" not in h and "infinite" not in h and h.count("sin(") == len(_sin_rads(h))


def test_the_flash_is_a_pale_tint_of_low_strength_never_a_saturated_red_area():
    for col in ("#ff0000", "#ff2200", "#e11d48", "#c00000", "#ff2d6f", "#e6f0ff", "#000000", "#0000ff"):
        (r, g, b), pk = _flash_peak_and_colour(_py(dict(BASE, flash=True, color=col)))
        hh, ll, ss = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
        assert ss <= 0.2 or ll >= 0.9, (col, (r, g, b))
        assert min(r, g, b) >= 200, ("a pale tint, so a red colour can never make a saturated red area", col, (r, g, b)) 
        assert pk <= 0.35, pk


@browser
def test_sampled_luminance_swings_stay_within_three_flashes(core_js):
    """In a real browser, sample the computed opacity of the bolt groups and the flash over 120 values of p and count rising runs: the bolt
    flicker and the flash together never rise more than 3 times (the draw-in is a stroke offset, not an opacity)."""
    blk = dict(BASE, flash=True, bolts=6, branches=4)
    js = ("var g=Array.prototype.slice.call(document.querySelectorAll('.lt-g')),f=document.querySelector('[data-lt=flash]');var root=document.querySelector('[data-lt=root]');var out=[];"
          "for(var i=0;i<=120;i++){root.style.setProperty('--p',i/120);var o=g.map(function(e){return +getComputedStyle(e).opacity;});var m=o.reduce(function(a,b){return a+b;},0)/o.length;"
          "out.push([m,f?+getComputedStyle(f).opacity:0]);}return out;")
    for html in (_py(blk), _gas_batch(core_js, [blk])[0]):
        series = _page(html, 1, 650, js)
        bolt, fl = [s[0] for s in series], [s[1] for s in series]
        assert abs(bolt[-1] - 1) < 1e-6 and fl[-1] == 0, "settled at p = 1: no flicker, no flash"

        def rises(v, eps=0.02):
            n, up, base = 0, False, v[0]
            for a, b in zip(v, v[1:]):
                if b > a + 1e-9:
                    if not up:
                        up, base = True, a
                else:
                    if up and a - base >= eps:
                        n += 1
                    up = False
            if up and v[-1] - base >= eps:
                n += 1
            return n
        assert rises(bolt) + rises(fl) <= 3, (rises(bolt), rises(fl))
        assert max(fl) <= 0.35 + 1e-6


